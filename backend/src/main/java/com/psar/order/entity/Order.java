package com.psar.order.entity;

import com.psar.common.entity.BaseEntity;
import jakarta.persistence.CascadeType;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.OneToMany;
import jakarta.persistence.OrderBy;
import jakarta.persistence.Table;
import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import org.hibernate.annotations.Generated;

import java.math.BigDecimal;
import java.time.Instant;
import java.util.ArrayList;
import java.util.List;
import java.util.UUID;

/**
 * An order with a snapshot of the delivery address, company name and product prices taken at checkout:
 * later edits to the address, company or product never change it. Change the status only through
 * the order services, which check {@link OrderStatus#canMoveTo} and write the history row.
 */
@Getter
@Setter
@NoArgsConstructor
@Entity
@Table(name = "orders")
public class Order extends BaseEntity {

    @Column(name = "public_id", nullable = false, unique = true, updatable = false)
    private UUID publicId = UUID.randomUUID();

    /** Generated by the database on insert (ORD-000001); don't set it. */
    @Generated
    @Setter(AccessLevel.NONE)
    @Column(name = "order_no", nullable = false, unique = true, insertable = false, updatable = false, length = 20)
    private String orderNo;

    @Column(name = "user_id", nullable = false, updatable = false)
    private Long userId;

    @Enumerated(EnumType.STRING)
    @Column(name = "status", nullable = false, length = 30)
    private OrderStatus status;

    @Enumerated(EnumType.STRING)
    @Column(name = "payment_method", nullable = false, length = 20, updatable = false)
    private PaymentMethod paymentMethod;

    @Column(name = "expires_at")
    private Instant expiresAt;

    // ---- delivery snapshot -----------------------------------------------------------------------

    @Enumerated(EnumType.STRING)
    @Column(name = "delivery_type", nullable = false, length = 20, updatable = false)
    private DeliveryType deliveryType;

    @Column(name = "receiver_name", nullable = false, length = 100)
    private String receiverName;

    @Column(name = "receiver_phone", nullable = false, length = 30)
    private String receiverPhone;

    @Column(name = "province", nullable = false, length = 100)
    private String province;

    @Column(name = "shipping_address", nullable = false, columnDefinition = "TEXT")
    private String shippingAddress;

    @Column(name = "shipping_latitude", precision = 9, scale = 6)
    private BigDecimal shippingLatitude;

    @Column(name = "shipping_longitude", precision = 9, scale = 6)
    private BigDecimal shippingLongitude;

    @Column(name = "shipping_landmark")
    private String shippingLandmark;

    @Column(name = "delivery_company_id")
    private Long deliveryCompanyId;

    @Column(name = "delivery_company_name", length = 100)
    private String deliveryCompanyName;

    @Column(name = "courier_branch", length = 150)
    private String courierBranch;

    @Column(name = "tracking_no", length = 100)
    private String trackingNo;

    /** The driver (a STAFF user) for CITY orders. */
    @Column(name = "assigned_staff_id")
    private Long assignedStaffId;

    @Column(name = "assigned_at")
    private Instant assignedAt;

    // ---- money (always calculated on the backend) --------------------------------------------------

    @Column(name = "subtotal", nullable = false, precision = 12, scale = 2)
    private BigDecimal subtotal;

    @Column(name = "product_discount", nullable = false, precision = 12, scale = 2)
    private BigDecimal productDiscount = BigDecimal.ZERO.setScale(2);

    @Column(name = "order_discount", nullable = false, precision = 12, scale = 2)
    private BigDecimal orderDiscount = BigDecimal.ZERO.setScale(2);

    @Column(name = "reward_discount", nullable = false, precision = 12, scale = 2)
    private BigDecimal rewardDiscount = BigDecimal.ZERO.setScale(2);

    @Column(name = "delivery_fee", nullable = false, precision = 12, scale = 2)
    private BigDecimal deliveryFee;

    @Column(name = "total_amount", nullable = false, precision = 12, scale = 2)
    private BigDecimal totalAmount;

    @Column(name = "note", length = 500)
    private String note;

    @Setter(AccessLevel.NONE)
    @OneToMany(mappedBy = "order", cascade = CascadeType.ALL, orphanRemoval = true)
    @OrderBy("productId")
    private List<OrderItem> items = new ArrayList<>();

    public void addItem(OrderItem item) {
        item.setOrder(this);
        items.add(item);
    }
}
